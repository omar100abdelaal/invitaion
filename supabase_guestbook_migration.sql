-- ==============================================================================
-- SUPABASE MIGRATION: GUESTBOOK (دفتر التهاني)
-- Run this in your Supabase Dashboard: SQL Editor -> New Query -> Run
-- ==============================================================================

-- 1. Create table for wedding wishes
CREATE TABLE IF NOT EXISTS public.guestbook (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  author TEXT NOT NULL,
  text TEXT NOT NULL,
  likes INT DEFAULT 0 NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.guestbook ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Anyone can view wishes (Public SELECT)
CREATE POLICY "Allow public read"
ON public.guestbook
FOR SELECT
TO public
USING (true);

-- 4. Policy: Anyone can submit congratulations (Public INSERT)
CREATE POLICY "Allow public insert"
ON public.guestbook
FOR INSERT
TO public
WITH CHECK (true);

-- 5. Policy: Anyone can like congratulations (Public UPDATE on likes)
CREATE POLICY "Allow public update likes"
ON public.guestbook
FOR UPDATE
TO public
USING (true)
WITH CHECK (true);

-- 6. Enable Realtime on guestbook table
ALTER PUBLICATION supabase_realtime ADD TABLE public.guestbook;
